"""Draws the hammer and sickle and bakes it into emblem_data.py.

Dev-only (needs Pillow): python tools/make_emblem.py [preview.png]
The app itself only uses the baked PNGs, so it has no extra dependencies.
"""

import base64
import io
import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SIZES = [20, 22, 24, 26, 28, 30, 32, 34, 36, 38, 40, 44, 48, 52, 56, 60, 64, 72, 80, 96]
FG = (242, 243, 245)
BG = (21, 23, 28)  # widget background; PNGs are pre-blended onto it
K = 4  # drawing scale: 1000 design units -> 4000 px


def P(x, y):
    return (x * K, y * K)


def arc(cx, cy, r, a0, a1, n=240):
    return [P(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
              cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def thick_line(d, pts, w):
    pts = [P(*p) for p in pts]
    d.line(pts, fill=255, width=int(w * K), joint="curve")
    for x, y in (pts[0], pts[-1]):
        r = w * K / 2
        d.ellipse((x - r, y - r, x + r, y + r), fill=255)


def disc(d, x, y, r):
    d.ellipse((*P(x - r, y - r), *P(x + r, y + r)), fill=255)


def draw_mask() -> Image.Image:
    m = Image.new("L", (1000 * K, 1000 * K), 0)
    d = ImageDraw.Draw(m)

    # --- sickle blade: outer circle minus an offset inner circle -> crescent with a sharp tip
    c1, r1 = (480, 440), 340
    off, ang = 60, math.radians(-126)
    c2, r2 = (c1[0] + off * math.cos(ang), c1[1] + off * math.sin(ang)), 295
    tip_a, cut_a = -88.0, 126.0
    outer = arc(*c1, r1, tip_a, cut_a)
    # inner arc: from the cut back up to the tip, measured around c2
    ox, oy = c1[0] + r1 * math.cos(math.radians(cut_a)), c1[1] + r1 * math.sin(math.radians(cut_a))
    tx, ty = c1[0] + r1 * math.cos(math.radians(tip_a)), c1[1] + r1 * math.sin(math.radians(tip_a))
    in_cut = math.degrees(math.atan2(oy - c2[1], ox - c2[0])) - 6
    in_tip = math.degrees(math.atan2(ty - c2[1], tx - c2[0]))
    inner = arc(*c2, r2, in_cut, in_tip)
    d.polygon(outer + inner, fill=255)

    # --- sickle handle: collar, slender grip, rounded end
    cx, cy = ox + 10, oy - 22               # where the blade meets the handle
    thick_line(d, [(cx + 10, cy - 12), (cx - 30, cy + 22)], 78)   # collar
    thick_line(d, [(cx - 30, cy + 22), (cx - 95, cy + 70), (cx - 140, cy + 108)], 58)  # grip
    thick_line(d, [(cx - 140, cy + 108), (cx - 185, cy + 150)], 92)  # rounded butt

    # --- hammer: handle on the 45° diagonal, trapezoid head at the top-left
    thick_line(d, [(385, 355), (835, 805)], 84)
    d.polygon([P(170, 420), P(375, 215), P(560, 238), P(280, 530)], fill=255)

    return m


def bake() -> dict:
    mask = draw_mask()
    mask = mask.crop(mask.getbbox())
    w, h = mask.size
    side = max(w, h)
    sq = Image.new("L", (side, side), 0)
    sq.paste(mask, ((side - w) // 2, (side - h) // 2))

    out = {}
    for s in SIZES:
        a = sq.resize((s, s), Image.LANCZOS)
        img = Image.composite(Image.new("RGB", (s, s), FG), Image.new("RGB", (s, s), BG), a)
        buf = io.BytesIO()
        img.save(buf, "PNG", optimize=True)
        out[s] = base64.b64encode(buf.getvalue()).decode()
    return out, sq


def main():
    data, big = bake()
    lines = ['"""Pre-rendered hammer and sickle PNGs (generated by tools/make_emblem.py)."""', "", "PNG = {"]
    for s, b in data.items():
        lines.append(f'    {s}: "{b}",')
    lines.append("}")
    (ROOT / "emblem_data.py").write_text("\n".join(lines) + "\n", encoding="utf-8")
    if len(sys.argv) > 1:
        prev = Image.composite(Image.new("RGB", big.size, FG), Image.new("RGB", big.size, BG), big)
        prev.resize((400, 400), Image.LANCZOS).save(sys.argv[1])


if __name__ == "__main__":
    main()
